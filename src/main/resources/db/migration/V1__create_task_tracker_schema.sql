CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    sort_order INTEGER NOT NULL UNIQUE CHECK (sort_order > 0)
);

CREATE TABLE tasks (
    id UUID PRIMARY KEY,
    reference VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(300) NOT NULL,
    project_id BIGINT NOT NULL REFERENCES projects (id) ON DELETE RESTRICT,
    story_points INTEGER CHECK (story_points BETWEEN 0 AND 100),
    assigned_date DATE NOT NULL,
    done_date DATE,
    status VARCHAR(32) NOT NULL CHECK (
        status IN ('RESOLVED', 'REVIEWING', 'IN_PROGRESS', 'TEST', 'BLOCKED', 'SHELVED')
    ),
    notes VARCHAR(2000) NOT NULL DEFAULT '',
    CONSTRAINT done_after_assigned CHECK (done_date IS NULL OR done_date >= assigned_date)
);

CREATE INDEX idx_tasks_project ON tasks (project_id);
CREATE INDEX idx_tasks_status ON tasks (status);

CREATE TABLE task_assignees (
    task_id UUID NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    assignee VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    PRIMARY KEY (task_id, sort_order)
);
